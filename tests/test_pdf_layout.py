def doc(sections: int, table_rows: int = 0) -> str:
    rows = "".join(f"| item {i} | value {i} | note {i} |\n" for i in range(table_rows))
    out = "# Guide to Dhaka\n\nA short intro paragraph for the cover.\n\n"
    for i in range(1, sections + 1):
        out += f"## Section {i}\n\n" + ("Lorem ipsum dolor sit amet, consectetur adipiscing elit. " * 25) + "\n\n"
        if i == 3 and table_rows:
            out += "| a | b | c |\n|---|---|---|\n" + rows + "\n"
    return out


def page(md: str) -> str:
    return dom_convert._markdown_to_html_dom(md, title="Guide")


class PageHtml(unittest.TestCase):
    def test_no_boilerplate(self):
        h = page(doc(6))
        for bad in ("Autonomous Document Engine", "Official Document", "Generated by Autonomous Agent"):
            self.assertNotIn(bad, h)
        slides = dom_convert._markdown_to_html_dom("# A\n- x\n---\n# B\n- y", title="Deck", is_slides=True)
        self.assertNotIn("Generated by Autonomous Agent", slides)

    def test_long_document_gets_cover_and_contents(self):
        h = page(doc(6))
        self.assertIn('<section class="doc-cover">', h)
        self.assertIn('<nav class="doc-toc">', h)
        self.assertEqual(h.count('id="sec'), 6)
        self.assertEqual(h.count('<h1 class="doc-h1">'), 0)          # the title moved to the cover
        self.assertIn("A short intro paragraph for the cover.", h.split('<nav class="doc-toc">')[0])

    def test_four_sections_get_a_cover_but_no_contents(self):
        h = page(doc(4))
        self.assertIn('<section class="doc-cover">', h)
        self.assertNotIn('<nav class="doc-toc">', h)

    def test_short_document_is_left_plain(self):
        h = page(doc(2))
        self.assertNotIn('<section class="doc-cover">', h)
        self.assertIn('<h1 class="doc-h1">Guide to Dhaka</h1>', h)

    def test_page_footer_and_print_rules(self):
        h = page(doc(2))
        self.assertIn('counter(page)', h)
        self.assertIn('counter(pages)', h)
        self.assertIn("table-header-group", h)
        self.assertIn("break-inside: avoid", h)
        self.assertIn("break-after: avoid", h)

    def test_footer_title_cannot_break_out_of_the_css_string(self):
        h = doc_theme.render_doc_page('x"; } body { display:none } /*', ["<p>hi</p>"])
        self.assertNotIn('"x"; }', h)
        self.assertNotIn('content: "x"; }', h)

    def test_bengali_documents_declare_their_language(self):
        h = doc_theme.render_doc_page("t", ["<p>ঢাকা বাংলাদেশের রাজধানী</p>"])
        self.assertIn('<html lang="bn">', h)
        self.assertIn("Nirmala UI", h)


@unittest.skipUnless(pdf_render._find_chromium_binary(), "no Chrome/Edge to print with")
class RealPdf(unittest.TestCase):
    def _render(self, md):
        import pdfplumber
        out = Path(tempfile.mkdtemp()) / "t.pdf"
        self.assertTrue(pdf_render._render_html_to_pdf(page(md), out))
        with pdfplumber.open(out) as pdf:
            return [(pg.extract_text() or "") for pg in pdf.pages]

    def test_cover_contents_and_numbered_pages(self):
        pages = self._render(doc(6))
        self.assertGreaterEqual(len(pages), 4)
        self.assertIn("Guide to Dhaka", pages[0])
        self.assertNotIn("Page 1 of", pages[0])                      # no footer on the cover
        self.assertIn("Contents", pages[1])
        self.assertIn(f"Page 2 of {len(pages)}", pages[1])
        self.assertIn(f"Page {len(pages)} of {len(pages)}", pages[-1])

    def test_table_header_repeats_on_each_page(self):
        pages = self._render(doc(5, table_rows=70))
        with_rows = [p for p in pages if "item " in p]
        self.assertGreaterEqual(len(with_rows), 2)
        for p in with_rows:
            self.assertIn("a b c", p)

    def test_no_boilerplate_in_the_pdf(self):
        text = "\n".join(self._render(doc(6)))
        self.assertNotIn("Autonomous", text)
        self.assertNotIn("Official Document", text)


