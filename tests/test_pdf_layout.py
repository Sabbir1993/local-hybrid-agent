def jpeg(w=900, h=600) -> bytes:
    b = io.BytesIO()
    Image.new("RGB", (w, h), (40, 120, 200)).save(b, "JPEG")
    return b.getvalue()


PIC_DOC = "# Guide to Dhaka\n\nIntro.\n\n## One\n\ntext\n\nimage: Lalbagh Fort | caption=The fort\n\n## Two\n\nmore\n"


class PdfPictures(unittest.TestCase):
    def test_image_lines_are_listed_in_order(self):
        specs = dom_convert.image_specs(PIC_DOC + "\nimage: boats | source=generate\n")
        self.assertEqual([x["query"] for x in specs], ["Lalbagh Fort", "boats"])
        self.assertEqual(specs[1]["source"], "generate")

    def test_image_lines_inside_code_are_not_pictures(self):
        self.assertEqual(dom_convert.image_specs("```\nimage: not one\n```\n"), [])

    def test_without_a_picture_the_line_vanishes(self):
        h = dom_convert._markdown_to_html_dom(PIC_DOC, title="G")
        self.assertNotIn("image:", h)
        self.assertNotIn("pdfimg", h)

    def test_picture_becomes_a_captioned_data_uri_figure(self):
        info = {"data": jpeg(), "credit_host": "example.org", "credit_url": "https://example.org/p", "via": "web"}
        h = dom_convert._markdown_to_html_dom(PIC_DOC, title="G", images={0: info})
        self.assertIn('<figure class="doc-fig"><img src="data:image/jpeg;base64,', h)
        self.assertIn("The fort - example.org", h)
        self.assertNotIn("pdfimg", h)
        self.assertNotIn("https://example.org", h)             # nothing remote reaches the print page

    def test_chart_block_becomes_inline_svg(self):
        md = "# D\n\n## A\n\nchart: line | unit=%\n- 2024: 40%\n- 2025: 60%\n- 2026: 89%\n\nafter\n"
        h = dom_convert._markdown_to_html_dom(md, title="G")
        self.assertIn('<figure class="doc-chart"><svg', h)
        self.assertIn("<polyline", h)
        self.assertNotIn("PDFCHARTTOKEN", h)
        self.assertNotIn("chart:", h)

    def test_chart_from_a_table_with_two_series(self):
        md = "# D\n\nchart: bar\n| Y | Sales | Cost |\n|---|---|---|\n| 2024 | 10 | 7 |\n| 2025 | 14 | 9 |\n"
        h = dom_convert._markdown_to_html_dom(md, title="G")
        self.assertEqual(h.count("<rect"), 4 + 2)               # 4 bars + 2 legend swatches
        self.assertIn("Sales", h)

    def test_not_numbers_keeps_the_list_and_drops_the_chart_line(self):
        md = "# D\n\nchart: bar\n- alpha: high\n- beta: low\n"
        h = dom_convert._markdown_to_html_dom(md, title="G")
        self.assertNotIn("<svg", h)
        self.assertIn("alpha: high", h)

    def test_svg_escapes_labels(self):
        svg = pdf_charts.chart_svg({"kind": "bar", "unit": "", "labels": ["<script>x</script>", "b"],
                                    "series": [{"name": "", "values": [1.0, 2.0]}]})
        self.assertNotIn("<script>", svg)
        self.assertIn("&lt;script&gt;", svg)

    def test_every_chart_kind_draws(self):
        for kind in ("bar", "hbar", "line", "pie"):
            svg = pdf_charts.chart_svg({"kind": kind, "unit": "%", "labels": ["a", "b", "c"],
                                        "series": [{"name": "s", "values": [3.0, 5.0, 2.0]}]})
            self.assertTrue(svg.startswith("<svg") and svg.endswith("</svg>"), kind)
            self.assertNotIn("nan", svg.lower())


class PdfResolver(unittest.TestCase):
    def setUp(self):
        si._cache.clear()
        mock.patch.object(si.doc_store, "audit").start()
        self.addCleanup(mock.patch.stopall)

    def test_pictures_resolve_in_order_with_the_document_subject(self):
        seen = []

        async def fake(uid, q, why, anchors=()):
            seen.append((q, anchors))
            return {"data": b"x", "credit_host": "h", "credit_url": "u", "via": "web"}
        with mock.patch.object(si, "_from_web", fake):
            images, notes, used = asyncio.run(si.resolve_pdf(PIC_DOC + "\nimage: boats\n", 7))
        self.assertEqual(sorted(images), [0, 1])
        self.assertEqual(seen[0][0], "Lalbagh Fort")
        self.assertIn("dhaka", seen[0][1])
        self.assertTrue(used)

    def test_no_picture_gives_a_note_not_an_error(self):
        async def none(uid, q, why, anchors=()):
            why.append("web search is off for this chat")
            return None
        with mock.patch.object(si, "_from_web", none), mock.patch.object(si, "_generate", none):
            images, notes, used = asyncio.run(si.resolve_pdf(PIC_DOC, 7))
        self.assertEqual(images, {})
        self.assertTrue(any("picture 1" in n for n in notes))


class BengaliFallback(unittest.TestCase):
    def test_latin_text_keeps_helvetica(self):
        self.assertEqual(pdf_render._reportlab_font("plain text"), ("Helvetica", "Helvetica-Bold"))

    def test_bengali_text_gets_a_font_with_the_glyphs_when_one_is_installed(self):
        from core.doc_ops.pptx_ops import measure
        reg, bold = pdf_render._reportlab_font("ঢাকা বাংলাদেশ")
        if any(measure._find(f) for f in ("Nirmala.ttc", "NirmalaUI.ttf", "NotoSansBengali-Regular.ttf", "Shonar.ttf")):
            self.assertEqual(reg, "BnSans")
        else:
            self.assertEqual(reg, "Helvetica")

    def test_fallback_pdf_builds_for_bengali_and_strips_image_lines(self):
        import pdfplumber
        md = "# ঢাকা\n\nঢাকা বাংলাদেশের রাজধানী।\n\nimage: Dhaka skyline\n\nchart: bar\n- A: 1\n- B: 2\n"
        with tempfile.TemporaryDirectory() as d:
            out = Path(d) / "bn.pdf"
            with mock.patch.object(pdf_render, "_render_html_to_pdf", return_value=False):
                self.assertTrue(pdf_render._save_text_or_markdown_as_pdf(out, md))
            with pdfplumber.open(out) as pdf:
                text = "\n".join(pg.extract_text() or "" for pg in pdf.pages)
        self.assertNotIn("image:", text)
        self.assertNotIn("chart:", text)


class PdfCheck(unittest.TestCase):
    def _reportlab(self, pages):
        from reportlab.pdfgen import canvas
        buf = io.BytesIO()
        c = canvas.Canvas(buf)
        for draw in pages:
            draw(c)
            c.showPage()
        c.save()
        return buf.getvalue()

    def test_clean_document_has_no_findings(self):
        from core.agent_tools import pdf_check
        import pdfplumber  # noqa: F401
        if not pdf_render._find_chromium_binary():
            self.skipTest("no Chrome/Edge")
        out = Path(tempfile.mkdtemp()) / "c.pdf"
        self.assertTrue(pdf_render._render_html_to_pdf(page(doc(6)), out))
        self.assertEqual(pdf_check.check_pdf(out.read_bytes(), doc(6)), [])

    def test_blank_page_is_reported(self):
        from core.agent_tools import pdf_check
        def text(c):
            c.setFont("Helvetica", 14)
            for i in range(30):
                c.drawString(72, 780 - i * 22, f"A line of real content number {i} on this page")
        data = self._reportlab([text, lambda c: None, text])
        findings = pdf_check.check_pdf(data, "")
        self.assertTrue(any("page 2 is blank" in f for f in findings), findings)

    def test_stranded_heading_is_reported(self):
        from core.agent_tools import pdf_check
        def first(c):
            c.setFont("Helvetica", 12)
            for i in range(32):
                c.drawString(72, 780 - i * 20, f"Body line {i} of the first page, real words here")
            c.setFont("Helvetica-Bold", 16)
            c.drawString(72, 120, "Section Two")
        def second(c):
            c.setFont("Helvetica", 12)
            for i in range(30):
                c.drawString(72, 780 - i * 22, f"Body of section two, line {i}, real words here")
        data = self._reportlab([first, second, second])
        findings = pdf_check.check_pdf(data, "## Section Two\n")
        self.assertTrue(any("stranded" in f and "page 1" in f for f in findings), findings)

    def test_unreadable_input_gives_no_findings(self):
        from core.agent_tools import pdf_check
        self.assertEqual(pdf_check.check_pdf(b"not a pdf", ""), [])
        self.assertEqual(pdf_check.summary([]), "")
        self.assertIn("2 issue(s)", pdf_check.summary(["a", "b"]))

    def test_headings_are_read_from_markdown_outside_code(self):
        from core.agent_tools import pdf_check
        self.assertEqual(pdf_check.headings_of("# T\n## **Two**\n```\n## not\n```\n### Three"), ["T", "Two", "Three"])


@unittest.skipUnless(pdf_render._find_chromium_binary(), "no Chrome/Edge to print with")
class RealPdfFigures(unittest.TestCase):
    def test_picture_and_chart_reach_the_printed_pdf(self):
        import pdfplumber
        md = ("# Guide\n\nintro\n\n## A\n\nimage: boats | caption=Harbour\n\n## B\n\nchart: bar | unit=%\n- X: 40\n- Y: 60\n")
